const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({headless: true});
  const fixture = JSON.parse(fs.readFileSync('/artifacts/api-workspace-browser-fixture.json'));
  const origin = fixture.url;
  const failures = [];
  let checks = 0;
  for (const viewport of [{width: 1440, height: 1000}, {width: 390, height: 844}]) {
    const page = await browser.newPage({viewport});
    await page.context().addCookies(fixture.cookies);
    page.on('pageerror', error => failures.push(error.message));
    await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
    await page.goto(origin + '/teacher-portal/api/');
    await page.getByRole('heading', {name: 'API та обмін', exact: true}).waitFor();
    assert.equal(await page.locator('.api-source-card').count(), 1, 'The same site has one card with backup addresses');
    assert.match(await page.locator('.api-source-card').innerText(), /Автоматичне перемикання/);
    assert.equal(await page.locator('.api-advanced').getAttribute('open'), null);
    assert.equal(await page.locator('.api-addresses').getAttribute('open'), null);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'No horizontal page overflow');
    await page.screenshot({path: `/artifacts/api-workspace-${viewport.width}.png`, fullPage: true});
    checks += 5;
    await page.getByRole('link', {name: '+ Додати API', exact: true}).click();
    await page.locator('#add-api[open]').waitFor();
    await page.locator('#add-api summary').click();
    checks++;
    await page.locator('.api-addresses summary').click();
    assert.equal(await page.locator('.api-address-row').count(), 2);
    await page.getByRole('link', {name: '+ Резервна адреса', exact: true}).click();
    await page.getByRole('heading', {name: 'Додати резервну адресу', exact: true}).waitFor();
    assert.equal(await page.locator('input[name="backup_for"]').count(), 1);
    assert.equal(await page.locator('input[name="apply_to_all_classes"]').count(), 0);
    await page.screenshot({path: `/artifacts/api-backup-${viewport.width}.png`, fullPage: true});
    checks += 3;
    await page.goto(origin + '/notifications/');
    await page.getByRole('heading', {name: 'Сповіщення', exact: true}).waitFor();
    assert.equal(await page.locator('.api-notice').count(), 2);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path: `/artifacts/api-notifications-${viewport.width}.png`, fullPage: true});
    await page.locator('.api-notice').filter({hasText: 'Не вдалося перевірити зв’язок'}).click();
    await page.locator('#address[open]').waitFor();
    assert.match(page.url(), /#address$/);
    await page.waitForFunction(() => { const top = document.querySelector('#address').getBoundingClientRect().top; return top >= 0 && top < innerHeight; });
    await page.screenshot({path: `/artifacts/api-address-target-${viewport.width}.png`, fullPage: true});
    checks += 4;
    await page.goto(origin + '/notifications/');
    await page.locator('.api-notice').filter({hasText: 'Список учнів потребує підтвердження'}).click();
    await page.locator('#roster').waitFor();
    assert.match(page.url(), /#roster$/);
    await page.goto(origin + '/help/#api-start');
    await page.getByRole('heading', {name: 'API та обмін: інструкція простими словами'}).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path: `/artifacts/api-guide-${viewport.width}.png`, fullPage: true});
    checks += 2;
    await page.close();
  }
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
  await page.context().addCookies(fixture.cookies);
  page.on('pageerror', error => failures.push(error.message));
  await page.goto(origin + '/teacher-portal/api/');
  await page.locator('.api-addresses summary').click();
  await page.locator('.api-address-row').first().getByRole('button', {name: 'Перевірити зв’язок', exact: true}).click();
  await page.getByRole('heading', {name: 'API та обмін', exact: true}).waitFor();
  await page.goto(origin + '/notifications/');
  assert.equal(await page.locator('.api-notice').count(), 1, 'A successful check resolves only its own error');
  await page.locator('.api-notice').click();
  await page.locator('#roster button[name="action"]').click();
  await page.goto(origin + '/notifications/');
  await page.getByRole('heading', {name: 'Усе гаразд', exact: true}).waitFor();
  assert.equal(await page.locator('.api-notice').count(), 0);
  assert.equal(await page.locator('[data-api-notifications] .api-notice-count').count(), 0);
  await page.screenshot({path: '/artifacts/api-notifications-resolved.png', fullPage: true});
  assert.deepEqual(failures, [], 'No browser JavaScript errors');
  checks += 4;
  await browser.close();
  console.log(`PASS: ${checks} API workspace checks: desktop/mobile, backup grouping, exact issue links, expanded sections, persisted/resolved notices, guide and no overflow`);
})().catch(error => { console.error(error); process.exit(1); });
